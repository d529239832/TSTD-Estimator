def find_min_sum_indices(tail_emp_cdf_diff, num_groups=5):
    n = len(tail_emp_cdf_diff)
    group_size = 5*5
    min_indices = []

    start_index = 0
    for _ in range(num_groups):
        min_sum = float('inf')
        min_index = -1

        for i in range(start_index, n - group_size + 1):
            current_sum = np.sum(tail_emp_cdf_diff[i:i + group_size])
            if current_sum < min_sum:
                min_sum = current_sum
                min_index = i + group_size // 2  # 计算中间位的索引

        min_indices.append(min_index)
        start_index = min_index - group_size // 2 + group_size  # 下一个组的起点是当前组的终点

    return min_indices

